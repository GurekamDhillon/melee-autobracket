#!/usr/bin/env bash
# End-to-end happy path with the REAL game engine: one autobracket server (in-process
# verifier running the real `melee slpcheck`), one local melee_relay, two autobracket-client
# players whose engines play a scripted netplay game (Captain Falcon v Fox, Final
# Destination, 60 s timer, 4 stocks), a single-elimination event of two, best of 1.
# Exits 0 only if the game is counted and the event has a champion.
#
# Usage: scripts/e2e-real-engine.sh            (build first: cargo build --release -p
#        autobracket-server -p autobracket-client)
#
# Environment (defaults are this project's dev server paths):
#   MELEE        engine binary          (/home/gd/melee-engine/build/cargo/fast/melee)
#   MELEE_RELAY  relay binary           (/home/gd/melee-engine/build/cargo/fast/melee_relay)
#   PAD_DIR      dir with np_fight.txt / np_fight2.txt
#                                       (/home/gd/melee-engine/tools/rust-port/netplay)
#   ISO          your own NTSC 1.02 disc image
#                                       (/home/gd/Super Smash Bros. Melee (USA) (En,Ja) (v1.02).iso)
#   E2E_DIR      scratch directory, wiped and recreated; keep it outside the repository
#                                       (${TMPDIR:-/tmp}/autobracket-e2e)
#   AB_BIN       dir holding autobracket and autobracket-client (<repo>/target/release)
#   HTTP_PORT    server port on 127.0.0.1   (18311)
#   RELAY_PORT   relay UDP port on 127.0.0.1 (51711)
#   NP_PORT      host's netplay UDP port     (51712)
#   ENGINE_MODE  match (default): host_args/join_args replaced by a `--match` start (Falcon v
#                Fox on FD, pads np_fight.txt / np_fight2.txt);
#                css: the client's DEFAULT host_args/join_args plus only `--headless --no-audio`,
#                the players picking on the netplay character select (Mario v Fox on Battlefield,
#                pads generated by $PAD_DIR/gen_css_scripts.py)
#   HOST_MATCH   host's --match, match mode  (falcon,32)
#   GUEST_MATCH  guest's --match, match mode (fox)
#   LEGAL_STAGES ruleset.legal_stages        ([2, 3, 8, 28, 31, 32]); e.g. [31] makes the game illegal
#   UPLOAD_TIMEOUT_SECS  server upload_timeout_secs (120)
#   GAME_TIMEOUT_SECS    give up after this long waiting for both clients (600)
#   LIVE         1: also check the live relay: a viewer (scripts/live-viewer.mjs, needs node)
#                watches set 0 from the start, and its received event bytes must equal the
#                host's .slp `raw` element byte for byte (the engine must have --relay-url)
#   E2E_HOOK     optional command run in the background once both clients are playing, with
#                E2E_DIR URL EVENT_ID AB C1 C2 SERVER_PID exported (C1/C2 = the client pids). Used
#                for the failure scenarios in docs/real-engine-e2e.md; a hook that starts processes
#                appends their pids to $E2E_DIR/extra-pids so the trap kills them too.
#
# Every process this script starts is killed by its EXIT trap; nothing else is touched.
set -u -o pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/.." && pwd)"
MELEE="${MELEE:-/home/gd/melee-engine/build/cargo/fast/melee}"
MELEE_RELAY="${MELEE_RELAY:-/home/gd/melee-engine/build/cargo/fast/melee_relay}"
PAD_DIR="${PAD_DIR:-/home/gd/melee-engine/tools/rust-port/netplay}"
ISO="${ISO:-/home/gd/Super Smash Bros. Melee (USA) (En,Ja) (v1.02).iso}"
E2E_DIR="${E2E_DIR:-${TMPDIR:-/tmp}/autobracket-e2e}"
AB_BIN="${AB_BIN:-$repo/target/release}"
HTTP_PORT="${HTTP_PORT:-18311}"
RELAY_PORT="${RELAY_PORT:-51711}"
NP_PORT="${NP_PORT:-51712}"
ENGINE_MODE="${ENGINE_MODE:-match}"
HOST_MATCH="${HOST_MATCH:-falcon,32}"
GUEST_MATCH="${GUEST_MATCH:-fox}"
LEGAL_STAGES="${LEGAL_STAGES:-[2, 3, 8, 28, 31, 32]}"
UPLOAD_TIMEOUT_SECS="${UPLOAD_TIMEOUT_SECS:-120}"
GAME_TIMEOUT_SECS="${GAME_TIMEOUT_SECS:-600}"

AB="$AB_BIN/autobracket"
ABC="$AB_BIN/autobracket-client"
URL="http://127.0.0.1:$HTTP_PORT"
for f in "$MELEE" "$MELEE_RELAY" "$AB" "$ABC" "$PAD_DIR/np_fight.txt" "$PAD_DIR/np_fight2.txt" "$ISO"; do
  [ -e "$f" ] || { echo "e2e: missing $f" >&2; exit 2; }
done
case "$E2E_DIR" in "$repo"|"$repo"/*) echo "e2e: E2E_DIR must be outside the repository" >&2; exit 2;; esac

log() { printf '%s e2e: %s\n' "$(date +%H:%M:%S.%3N)" "$*"; }

pids=()
cleanup() {
  local p
  for p in "${pids[@]}"; do
    # The clients start each game in its own process group (pgid = the game's pid);
    # kill our children and any game group they lead.
    kill "$p" 2>/dev/null
  done
  if [ -f "$E2E_DIR/extra-pids" ]; then
    while read -r xp; do kill "$xp" 2>/dev/null; done <"$E2E_DIR/extra-pids"
  fi
  if [ -f "$E2E_DIR/game-pids" ]; then
    while read -r gp; do kill -9 -- "-$gp" 2>/dev/null; done <"$E2E_DIR/game-pids"
  fi
  wait 2>/dev/null
}
trap cleanup EXIT
trap 'exit 130' INT TERM

# Only a directory this script made (it carries a marker) is ever wiped.
if [ -e "$E2E_DIR" ] && [ -n "$(ls -A "$E2E_DIR" 2>/dev/null)" ] && [ ! -e "$E2E_DIR/.autobracket-e2e" ]; then
  echo "e2e: $E2E_DIR exists and was not made by this script; pick another E2E_DIR" >&2; exit 2
fi
rm -rf "$E2E_DIR"
mkdir -p "$E2E_DIR"
touch "$E2E_DIR/.autobracket-e2e"
cd "$E2E_DIR" || exit 2

# 1. Relay.
"$MELEE_RELAY" --port "$RELAY_PORT" --bind 127.0.0.1 --bind6 off --quiet >relay.log 2>&1 &
pids+=($!)

# 2. Organiser key and server config.
TO_PUB="$("$AB" keygen --out to.key)" || exit 2
cat >server.toml <<EOF
bind = "127.0.0.1:$HTTP_PORT"
db_path = "$E2E_DIR/autobracket.sqlite"
replay_dir = "$E2E_DIR/replays"
relay = "127.0.0.1:$RELAY_PORT"
to_keys = ["$TO_PUB"]
upload_timeout_secs = $UPLOAD_TIMEOUT_SECS

[verifier]
mode = "in_process"
engine = "$MELEE"
iso = "$ISO"
timeout_secs = 300
jobs = 2

[ruleset]
stocks = 4
timer_secs = 60
best_of = 1
best_of_finals = 1
legal_stages = $LEGAL_STAGES
EOF
"$AB" serve --config server.toml >server.log 2>&1 &
SERVER_PID=$!
pids+=($SERVER_PID)
for _ in $(seq 100); do grep -q "^listening on" server.log && break; sleep 0.1; done
grep -q "^listening on" server.log || { echo "e2e: server did not start"; cat server.log; exit 1; }
log "server: $(head -1 server.log)"

admin() { "$AB" admin --server "$URL" --key-file to.key "$@"; }

# State watcher: every change in games / uploads / sets / queue / events, timestamped.
cat >watch.py <<'PY'
import sqlite3, sys, time
db = sys.argv[1]
qs = {
  "events": "SELECT id, state FROM events",
  "sets": "SELECT event_id||'/'||set_id, state||' room='||ifnull(room_code,'-')||' '||wins0||'-'||wins1 FROM sets",
  "games": "SELECT id, state||' '||ifnull(verdict_json,'') FROM games",
  "uploads": "SELECT game_id||'/'||slot, uploaded_at FROM uploads",
  "queue": "SELECT id, state||' '||reason FROM queue",
}
seen = {}
while True:
    try:
        c = sqlite3.connect(f"file:{db}?mode=ro", uri=True, timeout=1)
        for t, q in qs.items():
            for k, v in c.execute(q):
                if seen.get((t, k)) != v:
                    seen[(t, k)] = v
                    print(f"{time.time():.3f} {t} {k} {v}", flush=True)
        c.close()
    except sqlite3.Error:
        pass
    time.sleep(0.1)
PY
python3 -I watch.py "$E2E_DIR/autobracket.sqlite" >watch.log 2>&1 &
pids+=($!)

# 3. Two players. Each client config gets engine templates for scripted, headless netplay
#    by match code (see docs/real-engine-e2e.md for why each default changes).
for p in 1 2; do
  mkdir -p "p$p"
  "$ABC" --config "p$p/client.toml" init --melee "$MELEE" --iso "$ISO" --work-dir "$E2E_DIR/p$p/work" >"p$p/init.log" 2>&1 \
    || { echo "e2e: init p$p failed"; cat "p$p/init.log"; exit 1; }
done
python3 -I - "$E2E_DIR/p1/client.toml" "$E2E_DIR/p2/client.toml" "$NP_PORT" "$HOST_MATCH" "$GUEST_MATCH" "$ENGINE_MODE" <<'PY'
import sys, tomllib, json
paths, np_port, host_match, guest_match, mode = sys.argv[1:3], sys.argv[3], sys.argv[4], sys.argv[5], sys.argv[6]
common_tail = ["--np-lan", "127.0.0.1", "--np-bind", "127.0.0.1",
               "--record", "{mrpl}", "--slp", "auto",
               "--time-secs", "{timer_secs}", "--max-frames", "9000"]
host = ["play", "--iso", "{iso}", "--verify-disc", "--headless", "--no-audio",
        "--netplay", "host", "--np-server", "{relay}", "--np-port", np_port,
        "--match", host_match, "--np-seed", "4242"] + common_tail
join = ["play", "--iso", "{iso}", "--verify-disc", "--headless", "--no-audio",
        "--netplay", "join", "{code}", "--np-server", "{relay}",
        "--match", guest_match] + common_tail
for path in paths:
    with open(path, "rb") as f:
        cfg = tomllib.load(f)
    if mode == "css":
        cfg["host_args"] += ["--headless", "--no-audio"]
        cfg["join_args"] += ["--headless", "--no-audio"]
    else:
        cfg["host_args"], cfg["join_args"] = host, join
    # TOML basic strings, integers, booleans and string arrays are valid JSON literals.
    out = "".join(f"{k} = {json.dumps(v)}\n" for k, v in cfg.items())
    with open(path, "w") as f:  # keeps the file's 0600 mode
        f.write(out)
PY
"$ABC" --config p1/client.toml register --server "$URL" --tag HostFalcon || exit 1
"$ABC" --config p2/client.toml register --server "$URL" --tag GuestFox || exit 1

# 4. Event: single elimination, best of 1; both sign up (p1 first = seed 1), start.
EVENT_ID="$(admin event create --name "Real engine e2e" --format single --best-of 1 | python3 -I -c 'import json,sys; print(json.load(sys.stdin)["id"])')" \
  || { echo "e2e: event create failed"; exit 1; }
"$ABC" --config p1/client.toml signup "$EVENT_ID" || exit 1
"$ABC" --config p2/client.toml signup "$EVENT_ID" || exit 1
admin event start "$EVENT_ID" >event-start.json || exit 1
log "event $EVENT_ID started"

# 5. Both clients play. The engine inherits the client's environment: each player gets
#    its own pad script; the hidden-window variables are not needed with --headless.
export MELEE_VOLUME=0 MELEE_PAD_IGNORE_ADAPTER=1 MELEE_NETPLAY_BIND=127.0.0.1
pad1="$PAD_DIR/np_fight.txt" pad2="$PAD_DIR/np_fight2.txt"
if [ "$ENGINE_MODE" = css ]; then
  mkdir -p "$E2E_DIR/css-pads"
  python3 "$PAD_DIR/gen_css_scripts.py" "$E2E_DIR/css-pads" >/dev/null || exit 2
  pad1="$E2E_DIR/css-pads/np_css_host.txt" pad2="$E2E_DIR/css-pads/np_css_guest.txt"
  export MELEE_NP_SCRIPT_NO_START=1  # the scripts' results-screen START must not pause a match
fi
MELEE_PAD_SCRIPT="$pad1" "$ABC" --config p1/client.toml play "$EVENT_ID" --poll-secs 1 >p1/play.log 2>&1 &
c1=$!; pids+=($c1)
MELEE_PAD_SCRIPT="$pad2" "$ABC" --config p2/client.toml play "$EVENT_ID" --poll-secs 1 >p2/play.log 2>&1 &
c2=$!; pids+=($c2)
log "clients started (pids $c1 $c2)"
if [ "${LIVE:-}" = 1 ]; then
  node "$here/live-viewer.mjs" watch "$URL" "$EVENT_ID" 0 "$E2E_DIR/live.bin" "$GAME_TIMEOUT_SECS" >live.log 2>&1 &
  LIVE_PID=$!
  pids+=($LIVE_PID)
fi
if [ -n "${E2E_HOOK:-}" ]; then
  ( export E2E_DIR URL EVENT_ID AB SERVER_PID C1=$c1 C2=$c2; exec bash -c "$E2E_HOOK" ) >hook.log 2>&1 &
  pids+=($!)
fi

# Record each game's pid (its process group) as it appears, for the cleanup trap, and
# sample CPU load while the engines run.
(
  while kill -0 "$c1" 2>/dev/null || kill -0 "$c2" 2>/dev/null; do
    for c in "$c1" "$c2"; do
      for gp in $(pgrep -P "$c" 2>/dev/null); do grep -qx "$gp" game-pids 2>/dev/null || echo "$gp" >>game-pids; done
    done
    # time, 1-minute load average, then pid:cpu-ticks (utime+stime) for each game process
    t="$(date +%s.%N) $(cut -d' ' -f1 /proc/loadavg)"
    [ -f game-pids ] && while read -r gp; do
      [ -r "/proc/$gp/stat" ] && t+=" $gp:$(awk '{print $14+$15}' "/proc/$gp/stat" 2>/dev/null)"
    done <game-pids
    echo "$t" >>load.log
    sleep 2
  done
) &
pids+=($!)

deadline=$((SECONDS + GAME_TIMEOUT_SECS))
rc1="" rc2=""
while [ $SECONDS -lt $deadline ]; do
  if [ -z "$rc1" ] && ! kill -0 "$c1" 2>/dev/null; then wait "$c1"; rc1=$?; log "client 1 exited $rc1"; fi
  if [ -z "$rc2" ] && ! kill -0 "$c2" 2>/dev/null; then wait "$c2"; rc2=$?; log "client 2 exited $rc2"; fi
  [ -n "$rc1" ] && [ -n "$rc2" ] && break
  sleep 1
done
[ -n "$rc1" ] && [ -n "$rc2" ] || log "timed out waiting for the clients"

# 6. Results.
curl -fsS "$URL/v1/events/$EVENT_ID" >event.json || echo '{}' >event.json
curl -fsS "$URL/" >page.html || true
admin queue list >queue.json 2>&1 || true
admin quarantine list >quarantine.json 2>&1 || true
if [ "${LIVE:-}" = 1 ]; then
  wait "$LIVE_PID"; live_rc=$?
  log "live viewer: exit $live_rc $(grep RESULT live.log)"
  host_slp="$(find p1/work -name '*.slp' | sort | head -1)"
  if [ "$live_rc" = 0 ] && [ -n "$host_slp" ] && node "$here/live-viewer.mjs" compare live.bin "$host_slp" >live-compare.log 2>&1; then
    log "live: $(cat live-compare.log) vs $host_slp"
  else
    log "live: FAILED $(cat live-compare.log 2>/dev/null)"
    LIVE_FAILED=1
  fi
  grep -h "^live:\|live" p1/work/*/engine.log 2>/dev/null | grep -i "relay\|live" | head -5
fi
log "p1: $(tail -1 p1/play.log)"
log "p2: $(tail -1 p2/play.log)"
python3 -I - "$E2E_DIR/autobracket.sqlite" <<'PY'
import sqlite3, sys
c = sqlite3.connect(sys.argv[1])
for row in c.execute("SELECT id, set_id, game_no, state, winner_slot, verdict_json, verifier_build, resim_json FROM games"):
    print("game", row)
for row in c.execute("SELECT game_id, slot, path, sha256, uploaded_at FROM uploads"):
    print("upload", row)
PY
# CPU use of each game process over the samples (100 ticks per second assumed).
python3 -I - load.log <<'PY'
import sys
first, last = {}, {}
for line in open(sys.argv[1]):
    f = line.split()
    t = float(f[0])
    for w in f[2:]:
        pid, _, ticks = w.partition(":")
        if ticks:
            first.setdefault(pid, (t, int(ticks)))
            last[pid] = (t, int(ticks))
for pid in first:
    (t0, k0), (t1, k1) = first[pid], last[pid]
    if t1 > t0:
        print(f"game pid {pid}: {100 * (k1 - k0) / 100 / (t1 - t0):.0f}% of one core over {t1 - t0:.0f} s")
PY
counted=$(python3 -I -c 'import sqlite3,sys; print(sqlite3.connect(sys.argv[1]).execute("SELECT COUNT(*) FROM games WHERE state=\"counted\"").fetchone()[0])' "$E2E_DIR/autobracket.sqlite")
state=$(python3 -I -c 'import json,sys; print(json.load(open(sys.argv[1])).get("summary",{}).get("state",""))' event.json)
log "games counted: $counted; event state: $state"
if [ "$counted" -ge 1 ] && [ "$state" = "complete" ] && [ -z "${LIVE_FAILED:-}" ]; then
  log "PASS"
  exit 0
fi
log "FAIL (logs in $E2E_DIR)"
exit 1
